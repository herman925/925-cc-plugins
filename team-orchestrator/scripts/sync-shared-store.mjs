// Deterministic runtime packaging; no installed plugin or user data is changed.
import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
const source=fileURLToPath(new URL('../../shared/team-store/',import.meta.url));
const targets=[fileURLToPath(new URL('../store/',import.meta.url)),fileURLToPath(new URL('../../team-orchestration-925/skills/team-orchestration-925/scripts/runtime/',import.meta.url))];
const check=process.argv.includes('--check');
// Codex and the Mod package the same writer-family implementation. Generate its
// release from the Mod manifest so a client bump cannot leave Codex fenced out.
const release=JSON.parse(await readFile(new URL('../.claude-plugin/plugin.json',import.meta.url),'utf8')).version;
if(!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(release))throw Error('Invalid shared writer release.');
const releaseBytes=Buffer.from(`// Generated by team-orchestrator/scripts/sync-shared-store.mjs; do not edit.\nexport const SHARED_WRITER = Object.freeze({client:'team-orchestrator',version:${JSON.stringify(release)}});\n`);
const releasePath=join(source,'src/runtime-release.mjs');
if(check){if(releaseBytes.toString()!==(await readFile(releasePath,'utf8')).replace(/\r\n/g,'\n'))throw Error('Shared writer release does not match the Mod manifest; run sync-shared-store.mjs.');}
else await writeFile(releasePath,releaseBytes);
const files=['api.mjs','index.mjs','contract.mjs','mod-native.mjs','mod-bridge.mjs','codex-native.mjs','codex-mcp.mjs','codex-setup.mjs',...(await readdir(join(source,'src'))).filter(n=>n.endsWith('.mjs')||n==='windows-thread-owner.ps1').map(n=>`src/${n}`)];
for(const target of targets)for(const name of files){
 const bytes=await readFile(join(source,name));
 if(check){if(!bytes.equals(await readFile(join(target,name))))throw Error(`Stale packaged store: ${name}`);}
 else{await mkdir(join(target,name.includes('/')?'src':''),{recursive:true});await writeFile(join(target,name),bytes);}
}
console.log(`${check?'Verified':'Packaged'} ${files.length} shared runtime files in ${targets.length} packages.`);
