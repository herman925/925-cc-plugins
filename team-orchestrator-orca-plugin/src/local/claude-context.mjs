import { createHash, randomUUID } from 'node:crypto';
import { constants } from 'node:fs';
import { open, mkdir, rename, unlink } from 'node:fs/promises';
import { isAbsolute, join, resolve } from 'node:path';

const count = value => Number.isSafeInteger(value) && value >= 0;
const samePath = (a,b) => typeof a==='string' && typeof b==='string' && isAbsolute(a) && isAbsolute(b) && resolve(a)===resolve(b);
export const claudeContextDirectory = userData => userData && join(userData,'plugins-data','herman925.team-orchestrator','claude-context');
export const claudeContextFile = (directory,{sessionId,path,paneKey}) => join(directory,createHash('sha256').update(JSON.stringify([sessionId,path,paneKey])).digest('hex')+'.json');
export const claudeBindingFile = (directory,paneKey) => join(directory,'binding-'+createHash('sha256').update(paneKey).digest('hex')+'.json');
export const statuslineBinding = (provider,shown) => ({...provider,paneKey:`${shown.tabId}:${shown.leafId}`,handle:shown.handle,ptyId:shown.ptyId,incarnationId:shown.incarnationId});
export async function registerStatuslineBinding(directory,binding) {
  if(!directory)return;
  const path=claudeBindingFile(directory,binding.paneKey),text=JSON.stringify(binding)+'\n';
  try{if((await readSmallFile(path)).text===text)return;}catch{}
  await mkdir(directory,{recursive:true,mode:0o700});await atomicFile(path,text);
}

export function statuslineSample(payload, paneKey, capturedAt=Date.now()) {
  if (!payload || typeof payload.session_id!=='string' || !payload.session_id || payload.session_id.length>200 || typeof paneKey!=='string' || !paneKey || paneKey.length>500 || !isAbsolute(payload.transcript_path||'') || !payload.transcript_path.endsWith('.jsonl')) return null;
  const cwd=payload.workspace?.current_dir??payload.cwd;
  if(!isAbsolute(cwd||''))return null;
  const window=payload.context_window;
  if(!window||typeof window!=='object')return null;
  const sample={schema:1,sessionId:payload.session_id,path:payload.transcript_path,paneKey,cwd,capturedAt,model:typeof payload.model?.id==='string'?payload.model.id.slice(0,256):null,context:null};
  if(window.current_usage===null)return sample;
  const usage=window.current_usage,parts=[usage?.input_tokens,usage?.cache_creation_input_tokens??0,usage?.cache_read_input_tokens??0];
  const limit=window.context_window_size;
  if(!parts.every(count)||!count(limit)||limit<=0)return null;
  const used=parts.reduce((sum,value)=>sum+value,0),percent=window.used_percentage;
  if(!count(used))return null;
  // Preserve the CLI's reported rounding when it agrees with its own input counts.
  const calculated=100*used/limit;
  if(percent!==null&&percent!==undefined&&(typeof percent!=='number'||!Number.isFinite(percent)||percent<0||Math.abs(percent-calculated)>1))return null;
  sample.context={used,limit,percent:typeof percent==='number'?percent:calculated,estimated:false,capturedAt,source:'claude-statusline'};
  return sample;
}

export async function readSmallFile(path, limit=65536) {
  const file=await open(path,constants.O_RDONLY|constants.O_NOFOLLOW|constants.O_NONBLOCK);
  try {
    const stat=await file.stat();if(!stat.isFile()||stat.size>limit)throw Error('Context data is not a bounded regular file.');
    const buffer=Buffer.alloc(limit+1),{bytesRead}=await file.read(buffer,0,buffer.length,0);
    if(bytesRead>limit)throw Error('Context data exceeded its size limit.');
    return {text:buffer.subarray(0,bytesRead).toString('utf8'),stat};
  }finally{await file.close();}
}
export async function atomicFile(path,text,mode=0o600) {
  const temporary=path+'.'+randomUUID()+'.tmp';
  try{const file=await open(temporary,'wx',mode);try{await file.writeFile(text);await file.sync();}finally{await file.close();}await rename(temporary,path);}
  finally{await unlink(temporary).catch(()=>{});}
}
export async function saveStatuslineSample(directory,sample) {
  if(!sample)return;
  await mkdir(directory,{recursive:true,mode:0o700});
  await atomicFile(claudeContextFile(directory,sample),JSON.stringify(sample)+'\n');
}
export async function readStatuslineContext({directory,provider,shown,transcript,transcriptStat,now=Date.now()}) {
  if(!directory)return undefined;
  try{
    const paneKey=`${shown.tabId}:${shown.leafId}`;
    const sample=JSON.parse((await readSmallFile(claudeContextFile(directory,{...provider,paneKey}),16384)).text);
    if(sample.schema!==1||sample.sessionId!==provider.sessionId||sample.path!==provider.path||sample.paneKey!==paneKey||!samePath(sample.cwd,shown.worktreePath)||!Number.isFinite(sample.capturedAt)||sample.capturedAt>now+5000)return undefined;
    // The same conversation can be resumed in a new PTY. Accept only a sample
    // generated by the currently running process, corroborated by the native tab.
    const binding=statuslineBinding(provider,shown);
    if(Object.entries(binding).some(([key,value])=>!value||sample.binding?.[key]!==value))return undefined;
    if(!sample.transcriptFile||sample.transcriptFile.dev!==transcriptStat.dev||sample.transcriptFile.ino!==transcriptStat.ino)return undefined;
    const previousTime=typeof transcript?.capturedAt==='number'?transcript.capturedAt:Date.parse(transcript?.capturedAt);
    if(transcript&&(!Number.isFinite(previousTime)||sample.capturedAt<previousTime))return undefined;
    if(sample.context===null)return null;
    const c=sample.context;
    if(!transcript||!count(c.used)||c.used!==transcript.used||!count(c.limit)||c.limit<=0||typeof c.percent!=='number'||!Number.isFinite(c.percent)||c.percent<0||Math.abs(c.percent-100*c.used/c.limit)>1)return undefined;
    return {used:c.used,limit:c.limit,percent:c.percent,estimated:false,capturedAt:sample.capturedAt,source:'claude-statusline'};
  }catch{return undefined;}
}
